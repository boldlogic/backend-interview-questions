MARKUP_HELP = """- **Разметка:** после реплики интервьюера — одна строка:
  - `> 📎 **База:** …` — **теория**; ссылка на банк
  - `> 📎 **Задача:** …` — **практика** (live coding, SQL, code review)
  - Статусы: ✅ в банке, ⚠️ частично, ❌ нет, 🔧 упражнение
"""

FRONT = """---
размечено: true
теория: {theory}
лайвкодинг: {live}
опыт: {exp}
---
"""


def apply(path: Path, inserts: list[tuple[str, str]], summary: str, theory: bool, live: bool, exp: bool) -> None:
    text = path.read_text(encoding="utf-8")
    if "> 📎" in text:
        raise SystemExit(f"already marked: {path}")

    # frontmatter
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            text = text[end + 5 :].lstrip("\n")
    text = FRONT.format(theory=str(theory).lower(), live=str(live).lower(), exp=str(exp).lower()) + text

    # insert Разметка block before ## Транскрипт
    marker = "## Транскрипт"
    if marker not in text:
        raise SystemExit(f"no transcript section: {path}")
    if "**Разметка:**" not in text.split(marker, 1)[0]:
        text = text.replace(marker, MARKUP_HELP + "\n" + marker, 1)

    # insert anchors (from end to start by position to keep indices stable)
    positions: list[tuple[int, str]] = []
    for anchor, note in inserts:
        idx = text.find(anchor)
        if idx < 0:
            raise SystemExit(f"anchor not found in {path.name}: {anchor!r}")
        # place after the full line containing the anchor
        line_end = text.find("\n", idx)
        if line_end < 0:
            line_end = len(text)
        # avoid double-insert at same point
        insert_at = line_end
        positions.append((insert_at, f"\n{note}\n"))

    for insert_at, note in sorted(positions, key=lambda x: x[0], reverse=True):
        text = text[:insert_at] + note + text[insert_at:]

    if not text.rstrip().endswith(summary.strip()):
        text = text.rstrip() + "\n\n" + summary.strip() + "\n"

    path.write_text(text, encoding="utf-8")
    print(f"OK {path.relative_to(ROOT)} inserts={len(inserts)}")


