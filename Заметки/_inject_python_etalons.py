def upsert_etalon(card_text: str, etalon_body: str) -> str:
    card_text = re.sub(
        r"\n\*\*Эталон на собесе:\*\*\n.*?(?=\n---\s*$|\Z)",
        "",
        card_text,
        flags=re.S,
    )
    card_text = card_text.rstrip()
    if not card_text.endswith("---"):
        card_text += "\n\n---"
    etalon_block = f"\n\n**Эталон на собесе:**\n{etalon_body}\n"
    return re.sub(r"\n---\s*$", etalon_block + "\n---", card_text)


def main() -> None:
    path = Path("18. Python.md")
    text = path.read_text(encoding="utf-8")
    parts = re.split(r"\n(?=### )", text)
    header, cards = parts[0], parts[1:]

    applied: list[str] = []
    skipped: list[str] = []
    new_cards: list[str] = []
    for card in cards:
        m = re.match(r"### (.+)\n", card)
        if not m:
            new_cards.append(card)
            continue
        title = m.group(1).strip()
        if title in etalons:
            new_cards.append(upsert_etalon(card, etalons[title]))
            applied.append(title)
        else:
            new_cards.append(card)
            skipped.append(title)

    out = header.rstrip() + "\n\n" + "\n".join(c.rstrip() + "\n" for c in new_cards)
    assert "[[" not in out
    path.write_text(out, encoding="utf-8")
    print("applied", len(applied))
    print("skipped", len(skipped))
    for s in skipped:
        print(" ", s)
    print("etalon blocks", out.count("**Эталон на собесе:**"))
    print("lit blocks", out.count("**По литературе:**"))


if __name__ == "__main__":
    main()
