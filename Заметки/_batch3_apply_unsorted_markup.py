def frontmatter(fm: dict) -> str:
    return (
        "---\n"
        "размечено: true\n"
        f"теория: {'true' if fm['теория'] else 'false'}\n"
        f"лайвкодинг: {'true' if fm['лайвкодинг'] else 'false'}\n"
        f"опыт: {'true' if fm['опыт'] else 'false'}\n"
        "---\n\n"
    )


def apply_one(rel: str, cfg: dict) -> None:
    path = ROOT / rel
    text = path.read_text(encoding="utf-8")
    if text.lstrip().startswith("---"):
        # strip existing fm
        end = text.find("\n---\n", 3)
        if end != -1:
            text = text[end + 5 :].lstrip("\n")

    if "📎 **База:**" in text or "📎 **Задача:**" in text:
        raise SystemExit(f"Already has markup? {rel}")

    lines = text.splitlines(keepends=True)
    # insert header after metadata block (before ## Транскрипт)
    out: list[str] = []
    header_done = False
    for line in lines:
        if not header_done and line.startswith("## Транскрипт"):
            if not out or not out[-1].endswith("\n\n"):
                if out and not out[-1].endswith("\n"):
                    out[-1] += "\n"
                out.append("\n")
            out.append(HEADER)
            if not HEADER.endswith("\n"):
                out.append("\n")
            out.append("\n")
            header_done = True
        out.append(line)

    # insert markup after matching lines
    markup = cfg["markup"]
    found = {k: False for k in markup}
    final: list[str] = []
    for line in out:
        final.append(line)
        stripped = line.rstrip("\n")
        if stripped in markup:
            final.append(markup[stripped] + "\n")
            found[stripped] = True

    missing = [k for k, v in found.items() if not v]
    if missing:
        raise SystemExit(f"Missing anchors in {rel}:\n" + "\n".join(missing))

    body = "".join(final).rstrip() + "\n\n" + cfg["summary"].rstrip() + "\n"
    path.write_text(frontmatter(cfg["fm"]) + body, encoding="utf-8")
    print(f"OK {rel} marks={len(markup)}")


def main() -> None:
    for rel, cfg in FILES.items():
        apply_one(rel, cfg)


if __name__ == "__main__":
    main()
