def apply() -> None:
    text = PATH.read_text(encoding="utf-8")
    if "> 📎" in text:
        raise SystemExit(f"already marked: {PATH}")

    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            text = text[end + 5 :].lstrip("\n")
    text = FRONT + text

    marker = "## Транскрипт"
    if marker not in text:
        raise SystemExit("no ## Транскрипт")
    if "**Разметка:**" not in text.split(marker, 1)[0]:
        text = text.replace(marker, MARKUP_HELP + "\n" + marker, 1)

    positions: list[tuple[int, str]] = []
    missing: list[str] = []
    for anchor, note in INSERTS:
        idx = text.find(anchor)
        if idx < 0:
            missing.append(anchor)
            continue
        # uniqueness
        if text.find(anchor, idx + 1) >= 0:
            raise SystemExit(f"ambiguous anchor: {anchor!r}")
        line_end = text.find("\n", idx)
        if line_end < 0:
            line_end = len(text)
        positions.append((line_end, f"\n{note}\n"))

    if missing:
        raise SystemExit("missing anchors:\n" + "\n".join(missing))

    for insert_at, note in sorted(positions, key=lambda x: x[0], reverse=True):
        text = text[:insert_at] + note + text[insert_at:]

    text = text.rstrip() + "\n\n" + SUMMARY.strip() + "\n"
    PATH.write_text(text, encoding="utf-8")

    n_base = sum(1 for _, n in INSERTS if "**База:**" in n)
    n_task = sum(1 for _, n in INSERTS if "**Задача:**" in n)
    c_ok = sum(1 for _, n in INSERTS if "**База:** ✅" in n)
    c_warn = sum(1 for _, n in INSERTS if "**База:** ⚠️" in n)
    c_no = sum(1 for _, n in INSERTS if "**База:** ❌" in n)
    print(f"OK inserts={len(INSERTS)} База={n_base} Задача={n_task} ✅={c_ok} ⚠️={c_warn} ❌={c_no}")


if __name__ == "__main__":
    apply()
